#!/bin/sh
# Builds Yoga as plain JavaScript (no WebAssembly) for runtimes like React
# Native's Hermes engine. It compiles the same Yoga release that yoga-layout
# ships, with the same flags, but with WASM=0, so layout results match.
#
# Needs git and Docker. Writes src/layout/yoga-js/yoga-asmjs.js, which is
# committed, so this only needs to run again when yoga-layout is upgraded.
set -eu

YOGA_VERSION=3.2.1   # must match the yoga-layout dependency in package.json
EMSDK_VERSION=3.1.28 # the emsdk version Yoga $YOGA_VERSION builds with

here=$(cd "$(dirname "$0")/.." && pwd)
out="$here/src/layout/yoga-js/yoga-asmjs.js"
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

git clone --quiet --depth 1 --branch "v$YOGA_VERSION" https://github.com/facebook/yoga.git "$tmp/yoga"

# Same build as yoga-layout, but emit JavaScript instead of WebAssembly.
cmake_file="$tmp/yoga/javascript/CMakeLists.txt"
# Closure is skipped because it is very slow when Docker emulates x86 (Apple
# Silicon); esbuild minifies the output below instead.
sed -e 's/-s WASM=1/-s WASM=0/' -e '/SINGLE_FILE=1/d' -e '/--closure 1/d' "$cmake_file" > "$cmake_file.new"
mv "$cmake_file.new" "$cmake_file"
grep -q 'WASM=0' "$cmake_file" || { echo "Could not switch the Yoga build to WASM=0" >&2; exit 1; }

docker run --rm --platform linux/amd64 \
  -v "$tmp/yoga":/src -w /src/javascript \
  "emscripten/emsdk:$EMSDK_VERSION" \
  sh -c 'emcmake cmake -S . -B build -DCMAKE_BUILD_TYPE=Release > /dev/null && cmake --build build -j4'

built="$tmp/yoga/javascript/binaries/yoga-wasm-base64-esm.js"
[ -f "$built" ] || { echo "Build output not found: $built" >&2; exit 1; }

{
  echo "/**"
  echo " * Yoga $YOGA_VERSION compiled to plain JavaScript with Emscripten $EMSDK_VERSION (WASM=0)."
  echo " * Generated by scripts/build-yoga-js.sh. Do not edit."
  echo " *"
  echo " * Copyright (c) Meta Platforms, Inc. and affiliates. MIT License."
  echo " * https://github.com/facebook/yoga"
  echo " */"
  # import.meta is only used to locate a .wasm file this build never loads,
  # and Metro (React Native) can't bundle it. Use the bare file name for that
  # path (new URL with no base would throw), and drop any other uses.
  sed -e 's#new URL(\(["'"'"']\)yoga-wasm-base64-esm\.wasm\1, *import\.meta\.url)\.href#"yoga-wasm-base64-esm.wasm"#g' \
      -e 's/import\.meta\.url/undefined/g' "$built" > "$tmp/yoga.js"
  # esbuild comes with tsup, which is already a dev dependency.
  (cd "$here" && node -e '
    const { createRequire } = require("module");
    const esbuild = createRequire(require.resolve("tsup"))("esbuild");
    const code = require("fs").readFileSync(process.argv[1], "utf8");
    process.stdout.write(esbuild.transformSync(code, { minify: true, format: "esm", target: "es2019" }).code);
  ' "$tmp/yoga.js")
} > "$out"

if grep -q 'import\.meta' "$out"; then echo "import.meta is still present in $out" >&2; exit 1; fi
if grep -q 'new URL(' "$out"; then echo "A new URL() call is still present in $out" >&2; exit 1; fi

echo "Wrote $out ($(wc -c < "$out" | tr -d ' ') bytes)"
